LETTER = dict(zip("ABCDEFGHIJKLMNOPQRSTUVWXYZ","艾比西迪伊弗吉希艾杰凯尔艾恩欧皮丘阿艾蒂优维达艾怀泽"))
TERMS = re.compile("|".join(re.escape(term) for term in sorted(PLACES, key=len, reverse=True)))


def hira(text):
    return "".join(chr(ord(letter)-96) if "ァ" <= letter <= "ヶ" else letter for letter in text)


@lru_cache(None)
def chinese(name):
    if name in MUNICIPALITIES:
        return MUNICIPALITIES[name]
    if name in PLACES:
        return PLACES[name]
    normalized = unicodedata.normalize("NFKC",name).replace("・","·")
    # Each mapped label is already Chinese and must survive the kana fallback.
    normalized = TERMS.sub(lambda match: PLACES[match.group()],normalized)
    reading = hira(normalized)
    reading = re.sub(r"[ぁ-ゖーゝゞ]+",lambda match: phonetic(match.group()),reading)
    reading = re.sub(r"[A-Za-z]", lambda match: LETTER[match.group().upper()], reading)
    return SIMPLIFIED.convert(JP_KANJI.convert(reading)).strip()


def phonetic(run):
    result = []
    while run:
        if run[:2] in KANA:
            result.append(KANA[run[:2]])
            run = run[2:]
        else:
            result.append(KANA.get(run[0],run[0]))
            run = run[1:]
    return "".join(result)
